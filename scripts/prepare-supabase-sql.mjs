import { readFile, writeFile, readdir } from "node:fs/promises";

// Build a single file for the dashboard. No network requests or credentials.
const directory = new URL("../supabase/migrations/", import.meta.url);
const migration = (
  await Promise.all(
    (await readdir(directory))
      .filter((name) => name.endsWith(".sql"))
      .sort()
      .map((name) => readFile(new URL(name, directory), "utf8")),
  )
).join("\n\n");
const output = new URL("../supabase/sql-editor-setup.sql", import.meta.url);
await writeFile(
  output,
  `-- My Beautiful Property: first installation through Supabase SQL Editor.
-- Generated by npm run supabase:prepare-sql; edit the migration source instead.
-- Select the intended project, then run this ENTIRE file in one query.
-- Existing objects with the same names cause an error and roll back this run.
-- If already installed, inspect the existing schema instead of deleting tables.

begin;

${migration.trim()}

notify pgrst, 'reload schema';
commit;

select 'MBP_SETUP_OK' as status;
`,
);
console.log("Prepared supabase/sql-editor-setup.sql. No remote changes made.");
const stories = await readFile(
  new URL("202610240001_property_stories.sql", directory),
  "utf8",
);
await writeFile(
  new URL("../supabase/sql-editor-property-stories.sql", import.meta.url),
  `-- My Beautiful Property: photo-based property stories, EXISTING installations.
-- Generated by npm run supabase:prepare-sql. Run this ENTIRE file in one query.
-- This adds optional website copy and a generation budget; it does not replace existing data.
begin;
${stories.trim()}
commit;
select 'MBP_PROPERTY_STORIES_OK' as status;
`,
);
